#!/usr/bin/env python3
"""Regenerate tailscale/web/desc.xml from tailscale/web/desc.template.html.

The My Cloud dashboard looks up the tag for the UI language (en-US, nl-NL, ...)
and has no fallback, so the same HTML is emitted under every language tag.
Run after editing the template:  python3 tools/gen-desc.py
"""
import os, sys
LANGS = ["en-US","fr-FR","it-IT","de-DE","es-ES","zh-CN","zh-TW","ko-KR","ja-JP","ru-RU",
         "pt-BR","cs-CZ","nl-NL","hu-HU","no-NO","pl-PL","sv-SE","tr-TR"]
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tailscale", "web")
body = open(os.path.join(root, "desc.template.html"), encoding="utf-8").read().strip()
if "]]>" in body:
    sys.exit("template must not contain ']]>'")
out = ['<?xml version="1.0" encoding="UTF-8"?>',
       '<!-- GENERATED by tools/gen-desc.py from desc.template.html; do not edit by hand. -->',
       '<!-- Shown on the app page inside the My Cloud dashboard (app_menu.js get_app_desc). -->',
       '<desc>']
for l in LANGS:
    out.append(f'  <{l}><![CDATA[{body}]]></{l}>')
out.append('</desc>\n')
path = os.path.join(root, "desc.xml")
new = "\n".join(out)
if "--check" in sys.argv:
    sys.exit(0 if open(path, encoding="utf-8").read() == new else "desc.xml is out of date: run tools/gen-desc.py")
open(path, "w", encoding="utf-8").write(new)
print("wrote", path)
